#!/usr/bin/env python3
"""ForceArtGS -> ForceArtGS-Physics, end to end (Phase 7 of the integration plan).

    python examples/01_forceartgs_end_to_end.py [--run <ForceArtGS run dir>] [--methods IntegralLS Backprop AKF PINN MLP]
                                                [--out outputs/example01]

Default input: tests/fixtures/forceartgs_synthetic_revolute_s0, an actual Level-B synthetic-scene output of ForceArtGS
(`joint_discovery.cli synthetic --kind revolute`). Its robot record is generated by forceartgs_synthetic_robot.py
(LeRobot parquet layout, reaction-sign wrench in EE axes) for a joint with I = 0.05 kg m^2, c = 0.15 N m s/rad.
This example accepts ONLY the bundled synthetic scene. For measured data use
04_samuele_pipeline.py, which requires observed forces and calibration provenance.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

import forceartgs_synthetic_robot as S
from forceartgs_physics import api
from forceartgs_physics.adapters import forceartgs as FA
from forceartgs_physics.export import write_dynamics_yaml

HERE = Path(__file__).resolve().parent
I_TRUE, C_TRUE = 0.05, 0.15


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", type=Path, default=HERE.parent / "tests/fixtures/forceartgs_synthetic_revolute_s0")
    ap.add_argument("--methods", nargs="+", default=["IntegralLS", "Backprop", "AKF"],
                    help="add PINN and MLP for the full comparison (GPU recommended: minutes per seed)")
    ap.add_argument("--out", type=Path, default=Path("outputs/example01"))
    a = ap.parse_args()
    fixture = (HERE.parent / "tests/fixtures/forceartgs_synthetic_revolute_s0").resolve()
    if a.run.resolve() != fixture:
        ap.error("synthetic demo only: use 04_samuele_pipeline.py for measured runs")
    a.out.mkdir(parents=True, exist_ok=True)

    # 1-2. load the ForceArtGS output and extract joint + q(t) (frame: the ForceArtGS world W = robot base_link)
    joint, traj = FA.load_discovery_run(a.run, frame="base_link")
    print(f"[1-2] ForceArtGS decision {joint.source['decision']!r} -> status {joint.status.value}; {joint.joint_type}, "
          f"axis {np.round(joint.axis, 4)}, origin {np.round(joint.origin, 4)} m, {len(traj.t_s)} samples "
          f"t = {traj.t_s[0]:.2f}..{traj.t_s[-1]:.2f} s, q span {np.ptp(traj.q):.4f} {joint.units['q']}")

    # 3. robot data -> force ON the object at the TCP, in base_link (reaction sign and EE axes undone)
    rec = S.robot_record("revolute", [1, 0, 0], [0, 0.1, 0.13], -np.radians(40), 1.1, I_TRUE, C_TRUE)
    try:
        pq = S.write_parquet(a.out / "episode_000000.parquet", rec)
        forces = FA.load_lerobot_parquet(pq, S.TCP_OFFSET, fps=50.0, frame="base_link")
        src = f"LeRobot parquet {pq}"
    except ImportError as exc:
        forces = FA.robot_forces_from_arrays(rec["frame_index"] / 50.0, rec["ee_pos"], rec["ee_rotvec"], rec["wrench"],
                                             S.TCP_OFFSET, frame="base_link")
        src = f"synthetic arrays (pyarrow unavailable: {exc})"
    inter = FA.interaction("forceartgs_synthetic_revolute", joint, traj, forces)
    print(f"[3] forces from {src}: {len(forces.t_s)} samples at 50 Hz, peak |F| {np.abs(forces.force_N).max():.3f} N")

    # 4-5. run the estimators and compare
    rows = {}
    for m in a.methods:
        t0 = time.perf_counter()
        r = api.identify(inter, m)
        p = r.parameters
        rows[m] = r
        print(f"[4-5] {m:10s} {r.status:4s} I = {p.inertia:.5f} {p.units['inertia']} ({100 * (p.inertia / I_TRUE - 1):+.2f} %)  "
              f"c = {p.damping:.5f} {p.units['damping']} ({100 * (p.damping / C_TRUE - 1):+.2f} %)  "
              f"fit nRMSE {r.fit_metrics['q_fit_nrmse_pct']:.3f} %  {time.perf_counter() - t0:.0f} s")
    print("      identifiability:", next(iter(rows.values())).identifiability["verdict"])

    # 6. save the identified parameters (full result + parameters only)
    best = rows["AKF"] if "AKF" in rows else next(iter(rows.values()))
    for m, r in rows.items():
        api.save_parameters(r, a.out / f"result_{m}.json")
    api.save_parameters(best.parameters, a.out / "parameters.json")
    print(f"[6] saved {a.out}/result_*.json and parameters.json")

    # 7. predict a NEW interaction with frozen parameters (different push: 25 deg in 0.8 s), from rest
    params = api.load_parameters(a.out / "parameters.json")
    rec2 = S.robot_record("revolute", [1, 0, 0], [0, 0.1, 0.13], -np.radians(25), 0.8, I_TRUE, C_TRUE)
    f2 = FA.robot_forces_from_arrays(rec2["frame_index"] / 50.0, rec2["ee_pos"], rec2["ee_rotvec"], rec2["wrench"],
                                     S.TCP_OFFSET, frame="base_link")
    t_eval = np.linspace(0, 0.8, 41)
    q_true = S.gt_q(t_eval, -np.radians(25), 0.8)[0]
    # q of the new push in the ForceArtGS sign convention (axis canonicalised to +x, same as the ground-truth axis)
    pred = api.predict(params, f2, joint, t_eval)
    ev = api.evaluate_prediction(pred, t_eval, q_true)
    print(f"[7] new interaction, frozen parameters: prediction nRMSE {ev['nrmse_pct']:.3f} % "
          f"(final q pred {pred.q[-1]:.4f} vs true {q_true[-1]:.4f} rad)")
    (a.out / "prediction_new_interaction.json").write_text(json.dumps(pred.to_dict(), indent=1))

    # 8. PArtTwin1D physics/dynamics.yaml
    y = write_dynamics_yaml(best, a.out / "physics" / "dynamics.yaml", sources=[str(a.run)])
    print(f"[8] PArtTwin1D dynamics written to {y}")


if __name__ == "__main__":
    main()
