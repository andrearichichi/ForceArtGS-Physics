"""Guarded PArtTwin1D export. Effective joint mass/inertia is kept in joint space.
Link mass, CoM and inertia tensor remain unknown, including for prismatic joints.
Failed, missing, conflicting or negative identifiability verdicts refuse the export.
"""
from __future__ import annotations

import json
import math

from ..schemas import NotIdentifiableError
from pathlib import Path


def _yaml(x, ind=0) -> str:
    sp = "  " * ind
    if isinstance(x, dict):
        if not x:
            return " {}"
        return "".join(f"\n{sp}{k}:" + (_yaml(v, ind + 1) if isinstance(v, (dict, list)) and v else " " + _scalar(v))
                       for k, v in x.items())
    if isinstance(x, list):
        if not x:
            return " []"
        if all(not isinstance(v, (dict, list)) for v in x):
            return " [" + ", ".join(_scalar(v) for v in x) + "]"
        return "".join(f"\n{sp}- " + _yaml(v, ind + 1).lstrip() for v in x)
    return " " + _scalar(x)


def _scalar(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, (list, dict)):
        return json.dumps(v)
    return json.dumps(str(v))


def dynamics_document(result, *, joint_name="articulation_joint", limits=None, extension_fit=None, sources=()) -> dict:
    result.require_exportable()
    p = result.parameters
    ident = result.identifiability
    coul = None
    if extension_fit is not None and extension_fit.get("physically_consistent") is not True:
        raise NotIdentifiableError("supplied extension fit is inconsistent or unassessed; physical export refused")
    if extension_fit and extension_fit.get("physically_consistent") is True:
        term = extension_fit.get("terms", {}).get("coulomb", {})
        if term.get("identifiable") is True:
            coul = term.get("value")
            if not isinstance(coul, (int, float)) or not math.isfinite(coul) or coul < 0:
                raise NotIdentifiableError("Coulomb export requires a finite non-negative identified coefficient")
    lim = limits or {}
    return {
        "schema": "parttwin.dynamics/v1",
        "mode": "identified",
        "units": {"length": "m", "mass": "kg", "time": "s", "angle": "rad", "inertia": "kg*m^2"},
        "links": {"static": {"mass_kg": None, "com_link_m": None, "inertia_com_link_kg_m2": None},
                  "moving": {"mass_kg": None,
                             "com_link_m": None, "inertia_com_link_kg_m2": None}},
        "joint": {"name": joint_name, "type": p.joint_type,
                  "limits": {"lower": lim.get("lower"), "upper": lim.get("upper"), "source": lim.get("source", "unknown")},
                  "damping": p.damping, "coulomb_friction": coul, "actuation": None},
        "contact_material": {"coefficient_friction": None, "restitution": None},
        "evidence": {"sources": list(sources) + [f"forceartgs_physics {result.estimator} on {', '.join(result.interactions)}"],
                     "assumptions": ["1-DoF model I q'' + c q' = tau (ForceSAPIEN viscous model)",
                                     "effective joint mass/inertia is not link mass, CoM or inertia tensor: link fields null"]},
        "joint_space_identification": {
            "estimator": result.estimator, "status": result.status, "model": p.model,
            ("effective_inertia_about_axis_kg_m2" if p.joint_type == "revolute" else "effective_mass_kg"): p.inertia,
            "damping": p.damping, "units": p.units, "uncertainty": p.uncertainty,
            "identifiability_verdict": ident.get("verdict"), "fit_metrics": result.fit_metrics,
            "provenance": result.provenance},
    }


def write_dynamics_yaml(result, path, **kw) -> Path:
    doc = dynamics_document(result, **kw)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# generated by forceartgs_physics.export.parttwin" + _yaml(doc) + "\n")
    return path
