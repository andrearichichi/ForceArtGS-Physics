def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def segments(path: Path, names: list[str]) -> dict[str, str]:
    """Exact source text of top-level defs/classes/assignments, decorators included."""
    text = path.read_text()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    found: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)):
            name = node.name
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name = node.target.id
        else:
            continue
        if name in names and name not in found:
            start = min([d.lineno for d in getattr(node, "decorator_list", [])] + [node.lineno])
            found[name] = "".join(lines[start - 1:node.end_lineno])
    missing = [n for n in names if n not in found]
    if missing:
        raise SystemExit(f"{path}: names not found {missing}")
    return found


def relativize(text: str, depth: int) -> str:
    """`from akf_pinn.x import y` -> `from <dots>x import y` for a file `depth` packages below akf_pinn."""
    dots = "." * (depth + 1)
    return re.sub(r"\bfrom akf_pinn\.", f"from {dots}", text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--comparison-root", type=Path, required=True)
    ap.add_argument("--akf-pinn-root", type=Path, required=True)
    a = ap.parse_args()
    roots = {"cmp": a.comparison_root.resolve(), "akf": a.akf_pinn_root.resolve()}
    prov = {"generator": "tools/vendor_validated.py", "roots": {"cmp": "comparison/freeartgs_all_objects", "akf": "AKF_PINN"},
            "akf_pinn_whole_files": {}, "modules": {}}
    src = roots["akf"] / "src" / "akf_pinn"
    for rel in AKF_FILES:
        text = (src / rel).read_text()
        depth = rel.count("/")
        new = relativize(text, depth)
        patches = []
        if new != text:
            patches.append("absolute `from akf_pinn.` imports rewritten as package-relative imports")
        if rel == "config.py":
            old = "import tomllib\n"
            assert old in new
            new = new.replace(old, "try:  # vendoring patch: Python 3.10 has no tomllib (only used by load_config)\n"
                                   "    import tomllib\nexcept ModuleNotFoundError:  # pragma: no cover\n    tomllib = None\n")
            patches.append("Python-3.10 guard around `import tomllib` (used only by the unused load_config)")
        dst = PKG / "akf_pinn" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(new)
        prov["akf_pinn_whole_files"][f"akf_pinn/{rel}"] = dict(origin=f"AKF_PINN/src/akf_pinn/{rel}", sha256=sha256(src / rel),
                                                              patches=patches)
    for sub in ("akf_pinn", "akf_pinn/data", "akf_pinn/filters", "akf_pinn/pinn"):
        (PKG / sub / "__init__.py").write_text('"""Vendored subset of the AKF_PINN library (see _validated/PROVENANCE.json)."""\n')
    for name, root, rel, names, header in MODULES:
        path = roots[root] / rel
        seg = segments(path, names)
        origin = f"{prov['roots'][root]}/{rel}"
        body = "\n\n".join(seg[n].rstrip("\n") for n in names)
        text = BANNER.format(origin=origin, sha=sha256(path)[:16], names=", ".join(names)) + "\n" + header + "\n\n" + body + "\n"
        (PKG / f"{name}.py").write_text(text)
        prov["modules"][f"{name}.py"] = dict(origin=origin, sha256=sha256(path), names=names)
    (PKG / "__init__.py").write_text(
        '"""Validated implementations used for the ForceSAPIEN A3 / B1-B10 benchmark, vendored verbatim.\n\n'
        'Nothing in this subpackage is a public API: use ``forceartgs_physics.estimators``.\n"""\n')
    (PKG / "PROVENANCE.json").write_text(json.dumps(prov, indent=1) + "\n")
    print("wrote", PKG)


if __name__ == "__main__":
    main()
